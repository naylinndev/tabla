import { useMemo, useState } from "react";
import { Clock, GripVertical, Minus, Plus, TableProperties } from "lucide-react";
import type { Driver } from "../lib/api";
import { quoteIdent } from "../lib/sql";
import { useApp, type Session } from "../lib/store";
import { Checkbox, Combobox } from "./controls";
import { SqlConfirm } from "./SqlConfirm";

interface Col {
  key: string;
  name: string;
  type: string;
  pk: boolean;
  auto: boolean;
  nullable: boolean;
  def: string;
}

const TYPES: Record<string, string[]> = {
  postgres: ["bigint", "integer", "text", "varchar(255)", "boolean", "numeric(12,2)", "double precision", "date", "timestamptz", "jsonb", "uuid", "bytea"],
  mysql: ["bigint", "int", "varchar(255)", "text", "tinyint(1)", "decimal(12,2)", "double", "date", "datetime", "timestamp", "json", "char(36)", "blob"],
  sqlite: ["INTEGER", "TEXT", "REAL", "NUMERIC", "BLOB"],
  clickhouse: ["UInt64", "UInt32", "Int64", "String", "LowCardinality(String)", "Bool", "Float64", "Decimal(12,2)", "Date", "DateTime", "DateTime64(3)", "UUID", "Array(String)"],
  duckdb: ["BIGINT", "INTEGER", "VARCHAR", "BOOLEAN", "DECIMAL(12,2)", "DOUBLE", "DATE", "TIMESTAMP", "TIMESTAMPTZ", "JSON", "UUID", "VARCHAR[]", "BLOB"],
  oracle: ["NUMBER(19)", "NUMBER(10)", "VARCHAR2(255)", "VARCHAR2(4000)", "CLOB", "BOOLEAN", "NUMBER(12,2)", "BINARY_DOUBLE", "DATE", "TIMESTAMP", "TIMESTAMP WITH TIME ZONE", "JSON", "RAW(16)", "BLOB"],
  mssql: ["bigint", "int", "nvarchar(255)", "nvarchar(max)", "bit", "decimal(12,2)", "float", "date", "datetime2", "datetimeoffset", "uniqueidentifier", "varbinary(max)"],
};

const newKey = () => crypto.randomUUID();

function idColumn(d: Driver): Col {
  // ClickHouse has no auto-increment; ids usually come from the application.
  if (d === "clickhouse") return { key: newKey(), name: "id", type: "UInt64", pk: true, auto: false, nullable: false, def: "" };
  return { key: newKey(), name: "id", type: d === "sqlite" ? "INTEGER" : d === "duckdb" ? "BIGINT" : d === "oracle" ? "NUMBER(19)" : "bigint", pk: true, auto: true, nullable: false, def: "" };
}

function timestamps(d: Driver): Col[] {
  const t = d === "postgres" ? "timestamptz" : d === "mysql" ? "timestamp" : d === "mssql" ? "datetime2" : d === "clickhouse" ? "DateTime" : d === "duckdb" ? "TIMESTAMPTZ" : d === "oracle" ? "TIMESTAMP WITH TIME ZONE" : "TEXT";
  const now = d === "oracle" ? "SYSTIMESTAMP" : d === "postgres" || d === "clickhouse" || d === "duckdb" ? "now()" : d === "mssql" ? "SYSDATETIME()" : "CURRENT_TIMESTAMP";
  return [
    { key: newKey(), name: "created_at", type: t, pk: false, auto: false, nullable: false, def: now },
    { key: newKey(), name: "updated_at", type: t, pk: false, auto: false, nullable: false, def: now },
  ];
}

/** CREATE TABLE for each engine, with auto-increment written the idiomatic way. */
function createTableSql(d: Driver, schema: string, table: string, cols: Col[]): string {
  // Oracle folds unquoted names to upper case; quoting lower-case ones would
  // force everyone to quote them forever after.
  const q = (s: string) => quoteIdent(d, d === "oracle" && s === s.toLowerCase() ? s.toUpperCase() : s);
  if (d === "clickhouse") {
    // Nullability is part of the type; the primary key becomes the MergeTree sorting key.
    const lines = cols.map((c) => {
      const ty = c.type.trim();
      const nullable = c.nullable && !c.pk && !/^(Nullable|LowCardinality\(Nullable)\(/.test(ty);
      return `  ${q(c.name.trim())} ${nullable ? `Nullable(${ty})` : ty}${c.def.trim() ? ` DEFAULT ${c.def.trim()}` : ""}`;
    });
    const pks = cols.filter((c) => c.pk).map((c) => q(c.name.trim()));
    return `CREATE TABLE ${q(schema)}.${q(table)} (\n${lines.join(",\n")}\n) ENGINE = MergeTree\nORDER BY ${pks.length ? `(${pks.join(", ")})` : "tuple()"}`;
  }
  // DuckDB has no auto-increment: the id comes from a sequence created first.
  const seq = `${q(schema)}.${q(`${table}_id_seq`)}`;
  const pks = cols.filter((c) => c.pk);
  const singleAutoPk = pks.length === 1 && pks[0].auto;
  const lines = cols.map((c) => {
    const parts = [q(c.name.trim())];
    if (d === "sqlite" && singleAutoPk && c.pk) {
      parts.push("INTEGER PRIMARY KEY AUTOINCREMENT");
      return "  " + parts.join(" ");
    }
    parts.push(c.type.trim());
    if (c.auto && (d === "postgres" || d === "oracle")) parts.push("GENERATED BY DEFAULT AS IDENTITY");
    // Oracle wants DEFAULT before NOT NULL.
    if (d === "oracle" && c.def.trim() && !c.auto) parts.push(`DEFAULT ${c.def.trim()}`);
    if (c.auto && d === "mssql") parts.push("IDENTITY(1,1)");
    if (c.auto && d === "duckdb") parts.push(`DEFAULT nextval('${seq.replace(/'/g, "''")}')`);
    if (!c.nullable || c.pk) parts.push("NOT NULL");
    if (c.auto && d === "mysql") parts.push("AUTO_INCREMENT");
    if (d !== "oracle" && c.def.trim() && !c.auto) parts.push(`DEFAULT ${c.def.trim()}`);
    return "  " + parts.join(" ");
  });
  if (pks.length && !(d === "sqlite" && singleAutoPk)) lines.push(`  PRIMARY KEY (${pks.map((c) => q(c.name.trim())).join(", ")})`);
  const tail = d === "mysql" ? " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4" : "";
  const before = d === "duckdb" && cols.some((c) => c.auto) ? `CREATE SEQUENCE ${seq};\n` : "";
  return `${before}CREATE TABLE ${q(schema)}.${q(table)} (\n${lines.join(",\n")}\n)${tail}`;
}

export function CreateTableDialog({ session, onClose }: { session: Session; onClose(): void }) {
  const d = session.connection.driver;
  const [name, setName] = useState("");
  const [cols, setCols] = useState<Col[]>(() => [idColumn(d), { key: newKey(), name: "name", type: d === "sqlite" ? "TEXT" : d === "mysql" ? "varchar(255)" : d === "mssql" ? "nvarchar(255)" : d === "clickhouse" ? "String" : d === "duckdb" ? "VARCHAR" : d === "oracle" ? "VARCHAR2(255)" : "text", pk: false, auto: false, nullable: true, def: "" }]);
  const [dragKey, setDragKey] = useState<string | null>(null);

  const problems = useMemo(() => {
    const p: string[] = [];
    if (!name.trim()) p.push("Name the table");
    if (session.tables.some((t) => t.name.toLowerCase() === name.trim().toLowerCase())) p.push(`A table named "${name.trim()}" already exists`);
    if (!cols.length) p.push("Add at least one column");
    const names = cols.map((c) => c.name.trim().toLowerCase());
    if (names.some((n) => !n)) p.push("Every column needs a name");
    if (new Set(names).size !== names.length) p.push("Column names must be unique");
    if (cols.some((c) => !c.type.trim())) p.push("Every column needs a type");
    if (d === "clickhouse" && cols.some((c) => c.auto)) p.push("ClickHouse has no auto-increment; generate ids in your app or use generateUUIDv4()");
    if (cols.filter((c) => c.auto).length > 1) p.push("Only one auto-increment column is allowed");
    if (cols.some((c) => c.auto && !c.pk)) p.push("Auto-increment columns must be the primary key");
    if (d === "sqlite" && cols.some((c) => c.auto) && cols.filter((c) => c.pk).length > 1) p.push("SQLite auto-increment needs a single-column primary key");
    if ([name, ...cols.map((c) => c.type + c.def)].some((v) => v.includes(";"))) p.push("Remove the ; characters");
    return p;
  }, [name, cols, session.tables, d]);

  const sql = problems.length ? "" : createTableSql(d, session.schema, name.trim(), cols);
  const patch = (key: string, p: Partial<Col>) =>
    setCols((cs) =>
      cs.map((c) => {
        if (c.key !== key) return c;
        const n = { ...c, ...p };
        if (p.auto) n.pk = true;
        if (p.pk === false) n.auto = false;
        return n;
      }),
    );

  return (
    <SqlConfirm
      session={session}
      title="Create table"
      description={`In ${d === "mysql" || d === "clickhouse" ? "database" : "schema"} ${session.schema}`}
      statements={sql ? [sql] : []}
      displayStatements={sql ? [sql] : problems.map((p) => `-- ${p}`)}
      confirmLabel="Create table"
      onDone={async () => {
        const st = useApp.getState();
        await st.refreshTables(session.id);
        st.openTable(session.id, session.schema, name.trim(), "structure");
      }}
      onClose={onClose}
    >
      <div className="field">
        <label>Table name</label>
        <input className="input mono" autoFocus placeholder="orders" value={name} onChange={(e) => setName(e.target.value)} spellCheck={false} />
      </div>
      <div className="sg-panel">
        <div className="sg ct" role="table">
          <div className="sg-row sg-head">
            <span />
            <span>Column</span>
            <span>Type</span>
            <span className="c">Primary</span>
            <span className="c">Auto inc.</span>
            <span className="c">Null</span>
            <span>Default</span>
            <span />
          </div>
          {cols.map((c) => (
            <div
              key={c.key}
              className={`sg-row ${dragKey === c.key ? "dragging" : ""}`}
              onDragOver={(e) => {
                if (!dragKey || dragKey === c.key) return;
                e.preventDefault();
                setCols((cs) => {
                  const a = [...cs];
                  const i = a.findIndex((x) => x.key === dragKey);
                  const j = a.findIndex((x) => x.key === c.key);
                  const [m] = a.splice(i, 1);
                  a.splice(j, 0, m);
                  return a;
                });
              }}
            >
              <span className="grip" draggable onDragStart={() => setDragKey(c.key)} onDragEnd={() => setDragKey(null)}>
                <GripVertical />
              </span>
              <input className="sg-in strong" value={c.name} placeholder="column_name" onChange={(e) => patch(c.key, { name: e.target.value })} spellCheck={false} />
              <Combobox className="sg-combo" value={c.type} suggestions={TYPES[d]} onChange={(v) => patch(c.key, { type: v })} />
              <span className="c">
                <Checkbox checked={c.pk} onChange={(v) => patch(c.key, { pk: v })} />
              </span>
              <span className="c">
                <Checkbox checked={c.auto} onChange={(v) => patch(c.key, { auto: v })} />
              </span>
              <span className="c">
                <Checkbox checked={c.nullable && !c.pk} disabled={c.pk} onChange={(v) => patch(c.key, { nullable: v })} />
              </span>
              <input className="sg-in" value={c.def} placeholder={c.auto ? "auto" : c.nullable ? "NULL" : ""} disabled={c.auto} onChange={(e) => patch(c.key, { def: e.target.value })} spellCheck={false} />
              <span className="c">
                <button className="icon-btn danger" style={{ width: 24, height: 24 }} title="Remove column" onClick={() => setCols((cs) => cs.filter((x) => x.key !== c.key))}>
                  <Minus size={13} />
                </button>
              </span>
            </div>
          ))}
        </div>
        <div className="sg-bar">
          <button className="btn ghost" onClick={() => setCols((cs) => [...cs, { key: newKey(), name: "", type: TYPES[d][d === "sqlite" ? 1 : 2], pk: false, auto: false, nullable: true, def: "" }])}>
            <Plus /> Column
          </button>
          {!cols.some((c) => c.pk) && (
            <button className="btn ghost" onClick={() => setCols((cs) => [idColumn(d), ...cs])}>
              <TableProperties /> Add id
            </button>
          )}
          {!cols.some((c) => c.name === "created_at") && (
            <button className="btn ghost" onClick={() => setCols((cs) => [...cs, ...timestamps(d)])}>
              <Clock /> Add timestamps
            </button>
          )}
          <div className="spacer" />
          <span className="sg-count">{cols.length} columns</span>
        </div>
      </div>
      {problems.length > 0 && name && <p className="hint">{problems[0]}</p>}
    </SqlConfirm>
  );
}
